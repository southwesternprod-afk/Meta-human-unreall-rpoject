"""Write a one-click Unreal import script for a texture set.

The generated script (run with File > Execute Python Script in the editor):
  * imports T_<Name>_BaseColor / _ORM / _Normal with the right settings
    (sRGB on/off, Default / Masks / Normalmap compression)
  * creates the shared master material M_AAA_Master once (texture parameters
    plus Tiling, Tint, Roughness, Metallic, AO and Normal strength controls,
    usable on static and skeletal meshes)
  * creates MI_<Name>, an instance of the master with this set's textures

Artists then tweak MI_<Name> in the editor without touching the textures.
"""

from pathlib import Path

TEMPLATE = r'''"""Import the {name} texture set and make MI_{name} (generated by aaa-materials).

In Unreal: File > Execute Python Script... and pick this file. Keep the
Textures folder next to it.
"""

import os

import unreal

NAME = "{name}"
DEST = "{dest}"
MASTER = "{master_path}"
TILING = {tiling}

try:
    HERE = os.path.dirname(os.path.abspath(__file__))
except NameError:
    HERE = r"C:\PUT\THE\PATH\TO\THIS\FOLDER\HERE"

tools = unreal.AssetToolsHelpers.get_asset_tools()
assets = unreal.EditorAssetLibrary
mel = unreal.MaterialEditingLibrary


def tex_file(suffix):
    for folder in ("Textures", "."):
        path = os.path.join(HERE, folder, "T_{{}}_{{}}.png".format(NAME, suffix))
        if os.path.exists(path):
            return path
    raise FileNotFoundError("T_{{}}_{{}}.png not found next to this script".format(NAME, suffix))


def import_texture(suffix, srgb, compression):
    task = unreal.AssetImportTask()
    task.set_editor_property("filename", tex_file(suffix))
    task.set_editor_property("destination_path", DEST + "/Textures")
    task.set_editor_property("automated", True)
    task.set_editor_property("replace_existing", True)
    task.set_editor_property("save", True)
    tools.import_asset_tasks([task])
    tex = unreal.load_asset("{{}}/Textures/T_{{}}_{{}}".format(DEST, NAME, suffix))
    tex.set_editor_property("srgb", srgb)
    tex.set_editor_property("compression_settings", compression)
    assets.save_loaded_asset(tex)
    return tex


def expr(mat, cls, x, y, **props):
    node = mel.create_material_expression(mat, cls, x, y)
    for key, value in props.items():
        node.set_editor_property(key, value)
    return node


def build_master(base, orm, normal):
    """M_AAA_Master: parameterised PBR material shared by every set."""
    folder, name = MASTER.rsplit("/", 1)
    mat = tools.create_asset(name, folder, unreal.Material, unreal.MaterialFactoryNew())
    mat.set_editor_property("used_with_skeletal_mesh", True)
    S = unreal.MaterialSamplerType
    uv0 = expr(mat, unreal.MaterialExpressionTextureCoordinate, -1400, 0)
    tiling = expr(mat, unreal.MaterialExpressionScalarParameter, -1400, 120, parameter_name="Tiling", default_value=1.0)
    uv = expr(mat, unreal.MaterialExpressionMultiply, -1200, 40)
    mel.connect_material_expressions(uv0, "", uv, "A")
    mel.connect_material_expressions(tiling, "", uv, "B")

    def sampler(param, tex, kind, y):
        node = expr(mat, unreal.MaterialExpressionTextureSampleParameter2D, -1000, y,
                    parameter_name=param, texture=tex, sampler_type=kind)
        mel.connect_material_expressions(uv, "", node, "UVs")
        return node

    t_base = sampler("BaseColor", base, S.SAMPLERTYPE_COLOR, -500)
    t_orm = sampler("ORM", orm, S.SAMPLERTYPE_MASKS, 0)
    t_nrm = sampler("Normal", normal, S.SAMPLERTYPE_NORMAL, 500)

    def scalar(param, value, x, y):
        return expr(mat, unreal.MaterialExpressionScalarParameter, x, y, parameter_name=param, default_value=value)

    # base colour * tint
    tint = expr(mat, unreal.MaterialExpressionVectorParameter, -700, -380, parameter_name="Tint",
                default_value=unreal.LinearColor(1, 1, 1, 1))
    base_out = expr(mat, unreal.MaterialExpressionMultiply, -450, -450)
    mel.connect_material_expressions(t_base, "RGB", base_out, "A")
    mel.connect_material_expressions(tint, "", base_out, "B")
    mel.connect_material_property(base_out, "", unreal.MaterialProperty.MP_BASE_COLOR)

    # roughness remapped between RoughnessMin / RoughnessMax
    r_lerp = expr(mat, unreal.MaterialExpressionLinearInterpolate, -450, -60)
    mel.connect_material_expressions(scalar("RoughnessMin", 0.0, -700, -160), "", r_lerp, "A")
    mel.connect_material_expressions(scalar("RoughnessMax", 1.0, -700, -90), "", r_lerp, "B")
    mel.connect_material_expressions(t_orm, "G", r_lerp, "Alpha")
    mel.connect_material_property(r_lerp, "", unreal.MaterialProperty.MP_ROUGHNESS)

    # metallic * MetallicScale
    m_mul = expr(mat, unreal.MaterialExpressionMultiply, -450, 60)
    mel.connect_material_expressions(t_orm, "B", m_mul, "A")
    mel.connect_material_expressions(scalar("MetallicScale", 1.0, -700, 60), "", m_mul, "B")
    mel.connect_material_property(m_mul, "", unreal.MaterialProperty.MP_METALLIC)

    # AO blended by AOStrength
    one = expr(mat, unreal.MaterialExpressionConstant, -700, 160, r=1.0)
    ao = expr(mat, unreal.MaterialExpressionLinearInterpolate, -450, 180)
    mel.connect_material_expressions(one, "", ao, "A")
    mel.connect_material_expressions(t_orm, "R", ao, "B")
    mel.connect_material_expressions(scalar("AOStrength", 1.0, -700, 230), "", ao, "Alpha")
    mel.connect_material_property(ao, "", unreal.MaterialProperty.MP_AMBIENT_OCCLUSION)

    # normal blended towards flat by NormalStrength
    flat = expr(mat, unreal.MaterialExpressionConstant3Vector, -700, 420,
                constant=unreal.LinearColor(0, 0, 1, 1))
    n_lerp = expr(mat, unreal.MaterialExpressionLinearInterpolate, -450, 480)
    mel.connect_material_expressions(flat, "", n_lerp, "A")
    mel.connect_material_expressions(t_nrm, "RGB", n_lerp, "B")
    mel.connect_material_expressions(scalar("NormalStrength", 1.0, -700, 560), "", n_lerp, "Alpha")
    mel.connect_material_property(n_lerp, "", unreal.MaterialProperty.MP_NORMAL)

    mel.recompile_material(mat)
    assets.save_loaded_asset(mat)
    unreal.log("Created master material " + MASTER)
    return mat


def main():
    C = unreal.TextureCompressionSettings
    base = import_texture("BaseColor", True, C.TC_DEFAULT)
    orm = import_texture("ORM", False, C.TC_MASKS)
    normal = import_texture("Normal", False, C.TC_NORMALMAP)

    master = unreal.load_asset(MASTER) if assets.does_asset_exist(MASTER) else build_master(base, orm, normal)

    mi_path = "{{}}/MI_{{}}".format(DEST, NAME)
    if assets.does_asset_exist(mi_path):
        mi = unreal.load_asset(mi_path)
    else:
        mi = tools.create_asset("MI_" + NAME, DEST, unreal.MaterialInstanceConstant,
                                unreal.MaterialInstanceConstantFactoryNew())
    mel.set_material_instance_parent(mi, master)
    mel.set_material_instance_texture_parameter_value(mi, "BaseColor", base)
    mel.set_material_instance_texture_parameter_value(mi, "ORM", orm)
    mel.set_material_instance_texture_parameter_value(mi, "Normal", normal)
    mel.set_material_instance_scalar_parameter_value(mi, "Tiling", TILING)
    mel.update_material_instance(mi)
    assets.save_loaded_asset(mi)
    assets.sync_browser_to_objects([mi_path])
    unreal.log("Made " + mi_path + " - drag it onto a mesh, tweak Tiling/Tint/Roughness in the instance.")


main()
'''


def write_import_script(out_path, name, dest=None, master="/Game/Materials/AAA/M_AAA_Master", tiling=1.0):
    """Write Import_<name>_Unreal.py. `dest` defaults to /Game/Materials/AAA/<name>."""
    dest = dest or f"/Game/Materials/AAA/{name}"
    text = TEMPLATE.format(name=name, dest=dest, master_path=master, tiling=float(tiling))
    out_path = Path(out_path)
    out_path.write_text(text)
    return out_path
